export function translate(key, viewerLanguage) {
    const lang = viewerLanguage && TRANSLATIONS[viewerLanguage] ? viewerLanguage : 'en';
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
}

export function normalizeLang(lang) {
    if (!lang) return '';
    return String(lang).toLowerCase().split('-')[0];
}

export function getBrowserLanguage() {
    if (typeof navigator === 'undefined') return 'en';
    const lang = navigator.language || (Array.isArray(navigator.languages) ? navigator.languages[0] : 'en');
    return normalizeLang(lang);
}

export function resolveViewerLanguage({ getCookie, browserLanguage, supportedViewerLanguages = [] }) {
    const saved = getCookie('mimir_viewer_lang');
    if (saved) {
        return {
            viewerLanguage: normalizeLang(saved),
            viewerLanguageMode: 'manual'
        };
    }

    const browser = normalizeLang(browserLanguage);
    if (supportedViewerLanguages.includes(browser)) {
        return {
            viewerLanguage: browser,
            viewerLanguageMode: 'auto'
        };
    }
    if (supportedViewerLanguages.includes('en')) {
        return {
            viewerLanguage: 'en',
            viewerLanguageMode: 'auto'
        };
    }

    return {
        viewerLanguage: supportedViewerLanguages[0] || 'en',
        viewerLanguageMode: 'auto'
    };
}

export function collectManifestLanguages(obj) {
    const langs = new Set();
    const isLangMap = (val) => {
        if (!val || typeof val !== 'object' || Array.isArray(val)) return false;
        const keys = Object.keys(val);
        if (!keys.length) return false;
        const blocked = new Set(['id', 'type', '@id', '@type', '@context']);
        let match = 0;
        let total = 0;
        keys.forEach((key) => {
            const value = val[key];
            const looksLike = !blocked.has(key) && (key === 'none' || /^[a-z]{2,3}(-[a-z0-9]+)?$/i.test(key));
            const hasValue = Array.isArray(value) || typeof value === 'string';
            if (looksLike && hasValue) match += 1;
            total += 1;
        });
        return match > 0 && match === total;
    };
    const walk = (node) => {
        if (!node) return;
        if (Array.isArray(node)) {
            node.forEach(walk);
            return;
        }
        if (typeof node === 'object') {
            if (isLangMap(node)) {
                Object.keys(node).forEach((key) => langs.add(normalizeLang(key) || key));
                return;
            }
            Object.values(node).forEach(walk);
        }
    };
    walk(obj);
    return Array.from(langs).filter(Boolean);
}

export function pickManifestLanguage(langs, { manifestLanguage, viewerLanguage, browserLanguage } = {}) {
    const available = langs.map((lang) => normalizeLang(lang) || lang);
    if (!available.length) return '';

    const desired = manifestLanguage && manifestLanguage !== 'auto'
        ? normalizeLang(manifestLanguage)
        : '';
    if (desired && available.includes(desired)) return desired;

    const viewer = normalizeLang(viewerLanguage);
    if (viewer && available.includes(viewer)) return viewer;

    const browser = normalizeLang(browserLanguage);
    if (browser && available.includes(browser)) return browser;

    if (available.includes('none')) return 'none';
    if (available.includes('en')) return 'en';
    return available[0];
}

export function resolveLangValue(value, options = {}) {
    const {
        fallback = '',
        activeManifestLanguage,
        viewerLanguage,
        browserLanguage
    } = options;

    if (value == null) return fallback;
    if (typeof value === 'string') return value;
    if (Array.isArray(value)) {
        return resolveLangValue(value[0], options);
    }
    if (typeof value === 'object') {
        const keys = Object.keys(value);
        const isLangMap = keys.some((key) => key === 'none' || /^[a-z]{2,3}(-[a-z0-9]+)?$/i.test(key));
        if (isLangMap) {
            const preferences = [
                activeManifestLanguage,
                normalizeLang(viewerLanguage),
                normalizeLang(browserLanguage),
                'none',
                'en'
            ].filter(Boolean);
            const pick = (lang) => value[lang] ?? value[keys.find((key) => normalizeLang(key) === lang)];
            for (const lang of preferences) {
                const localized = pick(lang);
                if (localized != null) return resolveLangValue(localized, options);
            }
            return resolveLangValue(value[keys[0]], options);
        }
        return resolveLangValue(value[keys[0]], options);
    }
    return fallback;
}

export function getLanguageDisplayName(code, { viewerLanguage, noneLabel } = {}) {
    if (!code) return '';
    if (code === 'none') return noneLabel || 'None';
    try {
        const displayNames = new Intl.DisplayNames([viewerLanguage || 'en'], { type: 'language' });
        return displayNames.of(code) || code;
    } catch {
        return code;
    }
}
